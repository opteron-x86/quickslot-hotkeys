def _recipe(
    tid: str,
    material: str,
    seed: int,
    corner_cut: float,
    sel_tint: str = "selection",
    eq_tint: str = "equipped",
    border_w: float = 1.1,
    shadow_op: float = 0.45,
    glow_op: float = 0.26,
) -> Dict[str, Any]:
    return {
        "id": tid,
        "material": material,
        "seed": seed,
        "selectionTint": sel_tint,
        "equippedTint": eq_tint,
        "styleOverrides": {
            "cornerCut": corner_cut,
            "borderWidth": border_w,
            "shadowOpacity": shadow_op,
            "glowOpacity": glow_op,
            "accentLine": False,
        },
    }



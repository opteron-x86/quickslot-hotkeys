def resolve_recipe(recipe: Dict[str, Any]) -> Dict[str, Any]:
    """Merge a theme recipe on top of its base material preset."""
    mat_name = recipe.get("material", "oxblood_iron")
    base = deepcopy(MATERIALS.get(mat_name, MATERIALS["oxblood_iron"]))
    merged = deepcopy(base)
    for k, v in recipe.items():
        if k != "material":
            merged[k] = deepcopy(v)
    merged["material"] = mat_name
    merged.setdefault("seed", 17)
    merged.setdefault("id", "custom-theme")
    return merged
